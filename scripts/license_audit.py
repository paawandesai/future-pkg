"""Generate LICENSES.md from the Python and Node lockfile installs, and block forbidden licenses.

Usage:
  python scripts/license_audit.py                        # rewrite LICENSES.md (needs both installs)
  python scripts/license_audit.py --check python|node    # fail if that section is stale or forbidden

Each CI job checks one section: the Python job needs only uv, the Node job only pnpm (plus the
python3 that ships in the node:bookworm image).
"""

from __future__ import annotations

import difflib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "LICENSES.md"
# Licenses the guardrails forbid, plus anything that isn't a clear license (unknown, unlicensed,
# proprietary, "see license", empty). LGPL is allowed, so GPL and "General Public" match only when
# not part of LGPL or "Lesser"/"Library General Public". Tests: api/tests/test_license_gate.py.
FORBIDDEN = re.compile(
    r"(?<![L])\bA?GPL|(?<!Lesser )(?<!Library )General Public|Affero|SSPL|Server Side Public|BUSL"
    r"|\bBSL[- ]?1\.1|Business Source|\bNC\b|Non[- ]?Commercial|research|PolyForm|Commons[- ]Clause|Proprietary"
    r"|UNLICENSED|UNKNOWN|SEE LICEN[CS]E|^\s*$",
    re.I,
)
# Packages whose metadata is ambiguous but whose license was checked by hand (name -> note).
REVIEWED: dict[str, str] = {}


# Lockfile packages that install only on other platforms, so pip-licenses never sees them here.
# Licences checked on PyPI (2026-10-18). A new one that isn't listed shows as UNKNOWN and fails.
PLATFORM_ONLY = {
    "colorama": "BSD License (installed on Windows only)",
    "httpx2-jsfetch": "BSD-3-Clause (installed on Emscripten only)",
}


def lock_packages() -> dict[str, str]:
    text = (ROOT / "api" / "uv.lock").read_text()
    return dict(re.findall(r'\[\[package\]\]\nname = "([^"]+)"\nversion = "([^"]+)"', text))


def python_rows() -> list[tuple[str, str, str]]:
    raw = subprocess.run(
        # Every dependency group, and pip-licenses' own dependencies (--with-system), so the table
        # matches the lockfile rather than a filtered view of the environment.
        ["uv", "run", "--frozen", "-q", "--all-groups", "pip-licenses", "--format=json", "--from=mixed",
         "--with-system"],
        cwd=ROOT / "api", check=True, capture_output=True, text=True,
    ).stdout
    rows = [(p["Name"], p["Version"], p["License"]) for p in json.loads(raw)]
    seen = {n.lower().replace("_", "-") for n, _, _ in rows}
    for name, version in lock_packages().items():
        if name not in seen and name != "coachkg":
            rows.append((name, version, PLATFORM_ONLY.get(name, "UNKNOWN")))
    return sorted((n, v, lic) for n, v, lic in rows if n != "coachkg")


def node_rows() -> list[tuple[str, str, str]]:
    # pnpm reads the lockfile, so the list does not depend on how node_modules was hoisted.
    raw = subprocess.run(
        ["pnpm", "licenses", "list", "--json", "-r"], cwd=ROOT, check=True, capture_output=True, text=True
    ).stdout
    rows = set()
    for lic, pkgs in json.loads(raw).items():
        for p in pkgs:
            for v in p["versions"]:
                rows.add((p["name"], v, lic))
    return sorted(rows)


def render(py: list[tuple[str, str, str]], js: list[tuple[str, str, str]]) -> str:
    def table(rows: list[tuple[str, str, str]]) -> str:
        lines = ["| Package | Version | License |", "|---|---|---|"]
        lines += [f"| {n} | {v} | {lic} |" for n, v, lic in rows]
        return "\n".join(lines)

    return (
        "# Third-party licenses\n\n"
        "Generated by `scripts/license_audit.py` from the lockfiles (runtime, dev and deploy groups, all\n"
        "workspaces), as installed on linux-x64 (platform-specific optional packages differ elsewhere).\n"
        "CI fails if this file is stale or if a GPL/AGPL/SSPL/BUSL/non-commercial, unknown or\n"
        "proprietary license appears.\n\n"
        "## Tools and platform components outside the lockfiles (not linked into our code)\n\n"
        "| Tool | Version | License |\n|---|---|---|\n"
        "| gitleaks | 8.28.0 | MIT |\n| uv | pinned in CI image tag | MIT OR Apache-2.0 |\n"
        "| AWS Lambda Web Adapter (layer) | LambdaAdapterLayerX86:30 | Apache-2.0 |\n"
        "| boto3 in the Lambda python3.12 runtime | set by AWS | Apache-2.0 |\n"
        "| AWS CLI layer used by CDK BucketDeployment (aws-cdk-lib) | awscli 1.45.61 | Apache-2.0 |\n\n"
        f"## Python (api/uv.lock)\n\n{table(py)}\n\n## Node (pnpm-lock.yaml)\n\n{table(js)}\n"
    )


SECTIONS = {"python": "## Python (api/uv.lock)", "node": "## Node (pnpm-lock.yaml)"}


def section(text: str, heading: str) -> str:
    start = text.find(heading)
    if start < 0:
        return ""
    nxt = text.find("\n## ", start + len(heading))
    return text[start : nxt if nxt >= 0 else len(text)].strip()


def main() -> int:
    if "--check" in sys.argv:
        which = sys.argv[sys.argv.index("--check") + 1]
        rows = python_rows() if which == "python" else node_rows()
        expected = section(render(rows, []) if which == "python" else render([], rows), SECTIONS[which])
        current = section(OUT.read_text() if OUT.exists() else "", SECTIONS[which])
        bad = [r for r in rows if FORBIDDEN.search(r[2]) and r[0] not in REVIEWED]
        if current != expected:
            print(f"LICENSES.md {which} section is stale: run python scripts/license_audit.py", file=sys.stderr)
            diff = difflib.unified_diff(current.splitlines(), expected.splitlines(), "committed", "generated", lineterm="")
            print("\n".join(list(diff)[:60]), file=sys.stderr)
        for n, v, lic in bad:
            print(f"forbidden license: {n} {v} ({lic})", file=sys.stderr)
        return 1 if current != expected or bad else 0
    py, js = python_rows(), node_rows()
    OUT.write_text(render(py, js))
    bad = [r for r in py + js if FORBIDDEN.search(r[2]) and r[0] not in REVIEWED]
    for n, v, lic in bad:
        print(f"forbidden license: {n} {v} ({lic})", file=sys.stderr)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
