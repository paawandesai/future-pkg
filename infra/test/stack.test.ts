// Guardrails the deployed stack must keep. Run: pnpm --filter infra test
import assert from "node:assert/strict";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { App } from "aws-cdk-lib";
import { Match, Template } from "aws-cdk-lib/assertions";
import { DemoStack, type DemoStackProps, ORIGIN_HEADER } from "../lib/stack.ts";

const dir = (name: string) => {
  const d = mkdtempSync(join(tmpdir(), name));
  writeFileSync(join(d, "placeholder.txt"), "x");
  return d;
};
const build = (extra: Partial<DemoStackProps> = {}) =>
  Template.fromStack(
    new DemoStack(new App(), "Test", {
      env: { account: "111111111111", region: "us-east-1" },
      lambdaDir: dir("lambda"),
      webDir: dir("web"),
      modelFast: "fast",
      modelMain: "main",
      ...extra,
    }),
  );
const t = build();
const json = JSON.stringify(t.toJSON());
const resources = (tpl: Template, type: string) => Object.values(tpl.findResources(type)) as any[];
const apiFunction = (tpl: Template) =>
  resources(tpl, "AWS::Lambda::Function").find((f) => f.Properties.Environment?.Variables?.AUTH_MODE);

test("the API runs with Cognito auth, never mock", () => {
  const fns = t.findResources("AWS::Lambda::Function", {
    Properties: { Environment: { Variables: { PLAN_TABLE: Match.anyValue() } } },
  });
  const envs = Object.values(fns).map((f) => f.Properties.Environment.Variables);
  const api = envs.find((e) => "AUTH_MODE" in e);
  assert.ok(api, "API function not found");
  assert.equal(api.AUTH_MODE, "cognito");
  assert.ok(!json.includes('"AUTH_MODE":"mock"'));
});

test("sign-up is closed and coaches can't write their coach id", () => {
  t.hasResourceProperties("AWS::Cognito::UserPool", {
    AdminCreateUserConfig: { AllowAdminCreateUserOnly: true },
  });
  const clients = Object.values(t.findResources("AWS::Cognito::UserPoolClient"));
  assert.equal(clients.length, 1);
  const write: string[] = clients[0].Properties.WriteAttributes;
  assert.ok(!write.some((a) => a.includes("coach_id")), "coach_id must not be client-writable");
  assert.ok(clients[0].Properties.ReadAttributes.includes("custom:coach_id"));
});

test("no secret value or API key in the template; the function gets only the secret's name", () => {
  assert.ok(!/ANTHROPIC_FUTURE_API_KEY/.test(json));
  assert.ok(!/sk-ant-/.test(json));
  t.hasResourceProperties("AWS::SecretsManager::Secret", { Name: "future-pkg/anthropic-api-key" });
  const outputs = JSON.stringify(t.toJSON().Outputs);
  assert.ok(!/111111111111/.test(outputs), "outputs must not carry the account id");
});

test("every response from CloudFront carries noindex", () => {
  t.hasResourceProperties("AWS::CloudFront::ResponseHeadersPolicy", {
    ResponseHeadersPolicyConfig: {
      CustomHeadersConfig: {
        Items: Match.arrayWith([
          Match.objectLike({ Header: "X-Robots-Tag", Value: Match.stringLikeRegexp("noindex") }),
        ]),
      },
    },
  });
  const dist = Object.values(t.findResources("AWS::CloudFront::Distribution"))[0].Properties
    .DistributionConfig;
  for (const b of [dist.DefaultCacheBehavior, ...dist.CacheBehaviors]) assert.ok(b.ResponseHeadersPolicyId);
});

test("CloudFront sends the API a secret header, held only as a dynamic reference", () => {
  const dist = resources(t, "AWS::CloudFront::Distribution")[0].Properties.DistributionConfig;
  const apiOrigin = dist.Origins.find((o: any) => o.CustomOriginConfig);
  const [h] = apiOrigin.OriginCustomHeaders;
  assert.equal(h.HeaderName, ORIGIN_HEADER);
  const value = JSON.stringify(h.HeaderValue);
  assert.match(value, /\{\{resolve:secretsmanager:/, "the header value must be resolved at deploy time");
  const [secretId] = Object.entries(t.findResources("AWS::SecretsManager::Secret")).find(([id]) =>
    id.startsWith("OriginVerify"),
  )!;
  assert.ok(value.includes(secretId));
  const secret = t.toJSON().Resources[secretId].Properties;
  assert.ok(secret.GenerateSecretString, "the value is generated by Secrets Manager");
  // No secret in the template holds a value, and no other origin header is written literally.
  for (const s of resources(t, "AWS::SecretsManager::Secret"))
    assert.equal(s.Properties.SecretString, undefined);
  assert.ok(!/x-origin-verify"\s*,\s*"HeaderValue"\s*:\s*"/i.test(json));
  // The API gets the secret's ARN to read at runtime, never the value, and may read it.
  assert.deepEqual(apiFunction(t).Properties.Environment.Variables.ORIGIN_SECRET_ID, { Ref: secretId });
  assert.ok(JSON.stringify(t.findResources("AWS::IAM::Policy")).includes(secretId));
});

test("API concurrency is capped, and configurable", () => {
  assert.equal(apiFunction(t).Properties.ReservedConcurrentExecutions, 5);
  assert.equal(apiFunction(build({ apiConcurrency: 2 })).Properties.ReservedConcurrentExecutions, 2);
});

