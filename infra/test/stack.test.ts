test("security headers: no inline styles, a permissions policy, no server banners", () => {
  const cfg = resources(t, "AWS::CloudFront::ResponseHeadersPolicy")[0].Properties
    .ResponseHeadersPolicyConfig;
  const csp: string = cfg.SecurityHeadersConfig.ContentSecurityPolicy.ContentSecurityPolicy;
  assert.ok(!csp.includes("unsafe-inline"));
  assert.ok(cfg.CustomHeadersConfig.Items.some((h: any) => h.Header === "Permissions-Policy"));
  const removed = cfg.RemoveHeadersConfig.Items.map((h: any) => h.Header);
  assert.deepEqual(removed.sort(), ["server", "x-amz-server-side-encryption"]);
});

test("the app client has no OAuth flows and can't change a user's email", () => {
  const [client] = resources(t, "AWS::Cognito::UserPoolClient");
  assert.equal(client.Properties.AllowedOAuthFlows, undefined);
  assert.notEqual(client.Properties.AllowedOAuthFlowsUserPoolClient, true);
  const write: string[] = client.Properties.WriteAttributes;
  // An empty list would let the client write every standard attribute.
  assert.ok(write.length > 0 && !write.includes("email"));
});

test("pending access requests are counted from an index; the purge also sweeps that table", () => {
  t.hasResourceProperties("AWS::DynamoDB::Table", {
    GlobalSecondaryIndexes: [
      Match.objectLike({ IndexName: "by-status", KeySchema: [{ AttributeName: "status", KeyType: "HASH" }] }),
    ],
  });
  const purge = resources(t, "AWS::Lambda::Function").find(
    (f) => f.Properties.Environment?.Variables?.ACCESS_TABLE && !f.Properties.Environment.Variables.AUTH_MODE,
  );
  assert.ok(purge, "purge function must know the access table");
});

